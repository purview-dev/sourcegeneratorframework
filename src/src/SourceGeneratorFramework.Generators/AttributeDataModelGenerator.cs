	static void FromAttributeDataMethod(CodeWriter writer, AttributeDataModelTarget target)
	{
		MethodDeclarationOptions methodOptions = new(
			"FromAttributeData",
			TypeReference(target.StructName),
			TypeDeclarationAccessibility.Public
		)
		{
			IsStatic = true,
			Parameters = [new("attributeData", TypeReference("global::Microsoft.CodeAnalysis.AttributeData"))],
		};

		writer.Method(
			methodOptions,
			w =>
			{
				if (target.MatchByInheritance)
				{
					w.Line(
						"if (attributeData.AttributeClass is null || (!TargetAttribute.Equals(attributeData.AttributeClass) && !global::Purview.SourceGeneratorFramework.Helpers.TypeHelpers.InheritsFrom(attributeData.AttributeClass, TargetAttribute)))"
					);
				}
				else
				{
					w.Line("if (!TargetAttribute.Equals(attributeData.AttributeClass))");
				}
				w.Block(null, body => body.Line("return Empty;"));

				foreach (var property in target.Properties)
				{
					PropertyExtraction(w, property);
				}

				List<string> returnValues = ["true"];
				foreach (var property in target.Properties)
				{
					var value = ToCamelCase(property.PropertyName);
					returnValues.Add(property.IsNonNullableReferenceType ? value + "!" : value);
				}

				w.Line($"return new({string.Join(", ", returnValues)});");
			}
		);
	}

	static void TryFromAttributeDataMethod(CodeWriter writer, AttributeDataModelTarget target)
	{
		MethodDeclarationOptions methodOptions = new(
			"TryFromAttributeData",
			PurviewTypeLibrary.System.Boolean,
			TypeDeclarationAccessibility.Public
		)
		{
			IsStatic = true,
			Parameters =
			[
				new("attributeData", TypeReference("global::Microsoft.CodeAnalysis.AttributeData")),
				new("attribute", TypeReference(target.StructName), ParameterModifier.Out),
			],
		};

		writer.Method(
			methodOptions,
			w =>
			{
				w.Assignment("attribute", "Empty");
				if (target.MatchByInheritance)
				{
					w.Line(
						"if (attributeData.AttributeClass is null || (!TargetAttribute.Equals(attributeData.AttributeClass) && !global::Purview.SourceGeneratorFramework.Helpers.TypeHelpers.InheritsFrom(attributeData.AttributeClass, TargetAttribute)))"
					);
				}
				else
				{
					w.Line("if (!TargetAttribute.Equals(attributeData.AttributeClass))");
				}
				w.Block(null, body => body.Line("return false;"));

				foreach (var property in target.Properties)
				{
					PropertyExtraction(w, property);
				}

				List<string> returnValues = ["true"];
				foreach (var property in target.Properties)
				{
					var value = ToCamelCase(property.PropertyName);
					returnValues.Add(property.IsNonNullableReferenceType ? value + "!" : value);
				}

				w.Assignment("attribute", $"new({string.Join(", ", returnValues)})");

				w.Return("attribute.Exists");
			}
		);
	}

	static void PropertyExtraction(CodeWriter writer, AttributeDataModelProperty property)
	{
		var variableName = ToCamelCase(property.PropertyName);
		var typeName = GetNonNullableTypeName(property.FullyQualifiedTypeName);
		var localTypeName =
			property.IsNullableValueType ? typeName
			: property.IsNonNullableReferenceType ? typeName + "?"
			: property.FullyQualifiedTypeName;

		if (property.IsNestedModel)
		{
			writer.Line($"var {variableName} = {property.NestedModelTypeName}.FromAttributeData(attributeData);");
			return;
		}

		if (property.IsEnum)
		{
			EnumPropertyExtraction(writer, property, variableName);
			return;
		}

		var sources = property.Sources.AsImmutableArray();
		if (sources.IsEmpty)
		{
			writer.Line($"var {variableName} = default({typeName});");
			return;
		}

		if (sources.Length == 1)
		{
			var source = sources[0];
			if (property.HasDefaultValue)
			{
				SingleSourceExtractionWithDefault(
					writer,
					source,
					variableName,
					typeName,
					property.DefaultValueExpression
				);
			}
			else
			{
				SingleSourceExtraction(writer, source, variableName, typeName);
			}
			return;
		}

		MultiSourceExtraction(
			writer,
			sources,
			variableName,
			typeName,
			localTypeName,
			property.HasDefaultValue,
			property.DefaultValueExpression
		);
	}

	static void SingleSourceExtraction(CodeWriter writer, PropertySource source, string variableName, string typeName)
	{
		var extraction = GetSingleSourceExtractionExpression(source, variableName, typeName);
		writer.Line(extraction);
	}

	static void SingleSourceExtractionWithDefault(
		CodeWriter writer,
		PropertySource source,
		string variableName,
		string typeName,
		string defaultValueExpression
	)
	{
		var extraction = GetSingleSourceExtractionWithDefaultExpression(
			source,
			variableName,
			typeName,
			defaultValueExpression
		);
		writer.Line(extraction);
	}

	static void MultiSourceExtraction(
		CodeWriter writer,
		ImmutableArray<PropertySource> sources,
		string variableName,
		string typeName,
		string localTypeName,
		bool hasDefaultValue,
		string defaultValueExpression
	)
	{
		writer.Line($"{localTypeName} {variableName};");

		void Fallback(int index)
		{
			if (index >= sources.Length)
			{
				if (hasDefaultValue)
				{
					writer.Line($"{variableName} = {defaultValueExpression};");
				}
				return;
			}

			var source = sources[index];
			var isLast = index == sources.Length - 1 && !hasDefaultValue;
			var methodCall = GetTryGetMethodCall(source, variableName, typeName, declareVariable: false);

			if (isLast)
			{
				writer.Line(methodCall + ";");
			}
			else
			{
				writer.Line($"if (!{methodCall})");
				writer.Block(null, body => Fallback(index + 1));
			}
		}

		Fallback(0);
	}

	static void EnumPropertyExtraction(CodeWriter writer, AttributeDataModelProperty property, string variableName)
	{
		var sources = property.Sources.AsImmutableArray();
		var defaultValueExpression = property.HasDefaultValue ? property.DefaultValueExpression : "null";

		if (sources.Length == 1)
		{
			var expression = GetEnumSingleSourceExtractionExpression(sources[0], defaultValueExpression);
			writer.Line($"var {variableName} = {expression};");
			return;
		}

		EnumMultiSourceExtraction(writer, sources, variableName, defaultValueExpression);
	}

	[System.Diagnostics.CodeAnalysis.SuppressMessage("Style", "IDE0072:Add missing cases")]
	static string GetEnumSingleSourceExtractionExpression(PropertySource source, string defaultValueExpression)
	{
		return source.Source switch
		{
			AttributePropertySource.NamedArgument =>
				$"attributeData.GetEnumNamedArgument(\"{source.MappedName}\", {defaultValueExpression})",
			AttributePropertySource.ConstructorIndex =>
				$"attributeData.GetEnumConstructorArgument({source.ConstructorIndex}, {defaultValueExpression})",
			AttributePropertySource.ConstructorName =>
				$"attributeData.GetEnumConstructorArgument(\"{source.MappedName}\", {defaultValueExpression})",
			_ => throw new InvalidOperationException($"Unsupported enum property source: {source.Source}"),
		};
	}

	static void EnumMultiSourceExtraction(
		CodeWriter writer,
		ImmutableArray<PropertySource> sources,
		string variableName,
		string defaultValueExpression
	)
	{
		var typeName = "global::Microsoft.CodeAnalysis.TypedConstant";
		var tempName = $"__{variableName}Tc";

		writer.Line($"{typeName} {tempName} = default;");

		void Fallback(int index)
		{
			if (index >= sources.Length)
			{
				writer.Line($"{tempName} = default;");
				return;
			}

			var source = sources[index];
			var isLast = index == sources.Length - 1;
			var methodCall = GetTryGetMethodCall(source, tempName, typeName, declareVariable: false);

			if (isLast)
			{
				writer.Line(methodCall + ";");
			}
			else
			{
				writer.Line($"if (!{methodCall})");
				writer.Block(null, body => Fallback(index + 1));
			}
		}

		Fallback(0);

		writer.Line($"var {variableName} = {tempName}.ToEnumString() ?? {defaultValueExpression};");
	}

	static string GetSingleSourceExtractionExpression(PropertySource source, string variableName, string typeName)
	{
		var methodCall = GetTryGetMethodCall(source, variableName, typeName, declareVariable: true);
		// TryGet method declares the variable via out var, so we just call it.
		return methodCall + ";";
	}

	[System.Diagnostics.CodeAnalysis.SuppressMessage("Style", "IDE0072:Add missing cases")]
	static string GetSingleSourceExtractionWithDefaultExpression(
		PropertySource source,
		string variableName,
		string typeName,
		string defaultValueExpression
	)
	{
		return source.Source switch
		{
			AttributePropertySource.NamedArgument =>
				$"var {variableName} = attributeData.GetNamedArgument<{typeName}>(\"{source.MappedName}\", {defaultValueExpression});",
			AttributePropertySource.ConstructorIndex =>
				$"var {variableName} = attributeData.GetConstructorArgument<{typeName}>({source.ConstructorIndex}, {defaultValueExpression});",
			AttributePropertySource.ConstructorName =>
				$"var {variableName} = attributeData.GetConstructorArgument<{typeName}>(\"{source.MappedName}\", {defaultValueExpression});",
			AttributePropertySource.TypeArgument when source.MappedName is not null =>
				$"var {variableName} = attributeData.GetGenericTypeArgument<{typeName}>(\"{source.MappedName}\", {defaultValueExpression});",
			AttributePropertySource.TypeArgument =>
				$"var {variableName} = attributeData.GetGenericTypeArgument<{typeName}>({source.ConstructorIndex}, {defaultValueExpression});",
			_ => throw new InvalidOperationException($"Unsupported property source: {source.Source}"),
		};
	}

	[System.Diagnostics.CodeAnalysis.SuppressMessage("Style", "IDE0072:Add missing cases")]
	static string GetTryGetMethodCall(PropertySource source, string variableName, string typeName, bool declareVariable)
	{
		var outVariable = declareVariable ? $"out var {variableName}" : $"out {variableName}";
		return source.Source switch
		{
			AttributePropertySource.NamedArgument =>
				$"attributeData.TryGetNamedArgument<{typeName}>(\"{source.MappedName}\", {outVariable})",
			AttributePropertySource.ConstructorIndex =>
				$"attributeData.TryGetConstructorArgument<{typeName}>({source.ConstructorIndex}, {outVariable})",
			AttributePropertySource.ConstructorName =>
				$"attributeData.TryGetConstructorArgument<{typeName}>(\"{source.MappedName}\", {outVariable})",
			AttributePropertySource.TypeArgument when source.MappedName is not null =>
				$"attributeData.TryGetGenericTypeArgument<{typeName}>(\"{source.MappedName}\", {outVariable})",
			AttributePropertySource.TypeArgument =>
				$"attributeData.TryGetGenericTypeArgument<{typeName}>({source.ConstructorIndex}, {outVariable})",
			_ => throw new InvalidOperationException($"Unsupported property source: {source.Source}"),
		};
	}

	static string GetNonNullableTypeName(string typeName) =>
		typeName.EndsWith("?", StringComparison.Ordinal) ? typeName.Substring(0, typeName.Length - 1) : typeName;

	static string ToCamelCase(string value) =>
		string.IsNullOrEmpty(value) ? value : char.ToLowerInvariant(value[0]) + value.Substring(1);
}
